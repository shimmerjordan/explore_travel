/// ISO 3166-1 country/territory list grouped by continent, with Chinese
/// names. Used by the explore screen to render a complete world view even
/// for places we have no GeoJSON boundary data for (those show as 0% but
/// still appear in the grid).
///
/// Names are matched best-effort against [assets/boundaries/countries.json]
/// by either Chinese name or [code]. The asset is the source of truth for
/// computed exploration percent; this file is the source of truth for
/// "does this place exist".
